CREATE TABLE IF NOT EXISTS public.usuario (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_auth UUID UNIQUE,
  nome_usuario VARCHAR(100) NOT NULL UNIQUE,
  nome VARCHAR(150) NOT NULL,
  email VARCHAR(255) UNIQUE,
  tipo_usuario VARCHAR(40) NOT NULL DEFAULT 'Cliente',
  foto_perfil TEXT,
  banner_perfil TEXT,
  bio TEXT,
  data_nascimento DATE,
  genero VARCHAR(40),
  telefone VARCHAR(40)
);

CREATE TABLE IF NOT EXISTS public.artista (
  id_artista BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL UNIQUE REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  nome_artistico VARCHAR(150) NOT NULL,
  data_inicio DATE DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS public.redes_sociais (
  id_usuario BIGINT PRIMARY KEY REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  twitter TEXT,
  instagram TEXT,
  tiktok TEXT,
  youtube TEXT
);

CREATE TABLE IF NOT EXISTS public.privacidade_artista (
  id_usuario BIGINT PRIMARY KEY REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  perfil_publico BOOLEAN NOT NULL DEFAULT TRUE,
  exibir_redes_sociais BOOLEAN NOT NULL DEFAULT TRUE,
  exibir_informacoes BOOLEAN NOT NULL DEFAULT TRUE,
  aceitar_comissoes BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.categoria (
  id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_categoria VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.portifolio (
  id_portifolio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_artista BIGINT NOT NULL REFERENCES public.artista(id_artista) ON DELETE CASCADE,
  id_categoria BIGINT REFERENCES public.categoria(id_categoria) ON DELETE SET NULL,
  titulo VARCHAR(150) NOT NULL,
  descricao TEXT,
  preco NUMERIC(12, 2) NOT NULL DEFAULT 0,
  imagem TEXT NOT NULL,
  data_envio TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.favorito (
  id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  id_portifolio BIGINT NOT NULL REFERENCES public.portifolio(id_portifolio) ON DELETE CASCADE,
  PRIMARY KEY (id_usuario, id_portifolio)
);

CREATE TABLE IF NOT EXISTS public.opcao_comissao (
  id_opcao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_artista BIGINT NOT NULL REFERENCES public.artista(id_artista) ON DELETE CASCADE,
  titulo VARCHAR(120) NOT NULL,
  descricao TEXT NOT NULL,
  preco_inicial NUMERIC(12, 2) NOT NULL DEFAULT 0,
  prazo VARCHAR(80) NOT NULL,
  itens TEXT[] DEFAULT '{}',
  destaque BOOLEAN NOT NULL DEFAULT FALSE,
  ativa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.diretriz_comissao (
  id_diretriz BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_artista BIGINT NOT NULL REFERENCES public.artista(id_artista) ON DELETE CASCADE,
  titulo VARCHAR(120) NOT NULL,
  descricao TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.pedidos_principal (
  id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente BIGINT NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  id_artista BIGINT NOT NULL REFERENCES public.artista(id_artista) ON DELETE CASCADE,
  titulo VARCHAR(150) NOT NULL,
  descricao TEXT,
  referencias TEXT[] DEFAULT '{}',
  valor_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
  prazo VARCHAR(80),
  opcao_titulo VARCHAR(120),
  proposta_valor NUMERIC(12, 2),
  proposta_prazo VARCHAR(80),
  status_pedido VARCHAR(60) NOT NULL DEFAULT 'Pendente',
  status_comissao VARCHAR(60) NOT NULL DEFAULT 'Solicitada',
  data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  concluida_em TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.review (
  id_review BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_artista BIGINT NOT NULL REFERENCES public.artista(id_artista) ON DELETE CASCADE,
  id_cliente BIGINT NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  nota INTEGER NOT NULL CHECK (nota >= 1 AND nota <= 5),
  comentario TEXT,
  data_review TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.conversas (
  id_conversa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.participante_conversa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_conversa BIGINT NOT NULL REFERENCES public.conversas(id_conversa) ON DELETE CASCADE,
  id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.mensagens (
  id_mensagem BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_conversa BIGINT NOT NULL REFERENCES public.conversas(id_conversa) ON DELETE CASCADE,
  id_remetente BIGINT NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  conteudo TEXT NOT NULL,
  data_envio TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
