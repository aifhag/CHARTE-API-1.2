-- V5: integração do módulo "catálogo" (ex-charte-api1.0) ao schema do ChArte.
-- Idempotente: só adiciona o que falta; não altera dados nem remove colunas existentes.

-- usuario: colunas exigidas pelas entidades do catálogo (auth real é feita pelo Supabase Auth)
ALTER TABLE public.usuario ADD COLUMN IF NOT EXISTS senha_hash   VARCHAR(255) DEFAULT '';
ALTER TABLE public.usuario ADD COLUMN IF NOT EXISTS status_conta VARCHAR(20)  NOT NULL DEFAULT 'Ativo';
ALTER TABLE public.usuario ADD COLUMN IF NOT EXISTS data_criacao TIMESTAMP    NOT NULL DEFAULT NOW();

-- artista / categoria / portifolio
ALTER TABLE public.artista    ADD COLUMN IF NOT EXISTS biografia    TEXT;
ALTER TABLE public.categoria  ADD COLUMN IF NOT EXISTS descricao    TEXT;
ALTER TABLE public.portifolio ADD COLUMN IF NOT EXISTS status_venda VARCHAR(30);

-- arte (catálogo de artes à venda)
CREATE TABLE IF NOT EXISTS public.arte (
  id_arte      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_artista   BIGINT NOT NULL REFERENCES public.artista(id_artista)     ON DELETE CASCADE,
  id_categoria BIGINT NOT NULL REFERENCES public.categoria(id_categoria) ON DELETE RESTRICT,
  titulo       VARCHAR(150) NOT NULL,
  descricao    TEXT,
  preco        NUMERIC(10, 2) NOT NULL,
  disponivel   BOOLEAN NOT NULL DEFAULT TRUE
);

-- pedido / item_pedido (carrinho do catálogo; independente de pedidos_principal das comissões)
CREATE TABLE IF NOT EXISTS public.pedido (
  id_pedido   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario  BIGINT NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  status      VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
  data_pedido TIMESTAMP NOT NULL DEFAULT NOW(),
  valor_total NUMERIC(10, 2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.item_pedido (
  id_item        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido      BIGINT NOT NULL REFERENCES public.pedido(id_pedido) ON DELETE CASCADE,
  id_arte        BIGINT NOT NULL REFERENCES public.arte(id_arte)     ON DELETE RESTRICT,
  quantidade     INTEGER NOT NULL CHECK (quantidade > 0),
  preco_unitario NUMERIC(10, 2) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_arte_artista   ON public.arte(id_artista);
CREATE INDEX IF NOT EXISTS idx_arte_categoria ON public.arte(id_categoria);
CREATE INDEX IF NOT EXISTS idx_item_pedido    ON public.item_pedido(id_pedido);

-- RLS: acesso do backend via JDBC (role de serviço); bloqueia acesso direto anônimo via PostgREST
ALTER TABLE public.arte        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pedido      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.item_pedido ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS arte_leitura_publica ON public.arte;
CREATE POLICY arte_leitura_publica ON public.arte FOR SELECT USING (true);
