CREATE TABLE IF NOT EXISTS public.pagamentos (
  id_pagamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido BIGINT NOT NULL REFERENCES public.pedidos_principal(id_pedido) ON DELETE CASCADE,
  metodo VARCHAR(40) NOT NULL DEFAULT 'Pix',
  status_pagamento VARCHAR(40) NOT NULL DEFAULT 'Pendente',
  gateway_payment_id TEXT UNIQUE,
  checkout_url TEXT,
  gateway_status TEXT DEFAULT 'PENDING'
);

ALTER TABLE public.pagamentos
  ADD COLUMN IF NOT EXISTS gateway_payment_id TEXT,
  ADD COLUMN IF NOT EXISTS checkout_url TEXT,
  ADD COLUMN IF NOT EXISTS gateway_status TEXT DEFAULT 'PENDING';

CREATE UNIQUE INDEX IF NOT EXISTS idx_pagamentos_gateway_payment_id
  ON public.pagamentos(gateway_payment_id)
  WHERE gateway_payment_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_pagamentos_id_pedido
  ON public.pagamentos(id_pedido);
